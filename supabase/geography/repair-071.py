# Generates migration 071: repairs the Geography badge emoji and accented
# Pin the map place names that reached the live database garbled.
#
# Cause: 069 and 070 were put on the clipboard with `pbcopy` from a shell with
# no UTF-8 locale, which hands other apps the bytes as Mac Roman. Supabase
# then stored the turtle as 'üê¢' instead of 🐢, and Yaoundé as 'Yaound√©'.
#
# The repair carries every value as base64 inside convert_from(decode(...)),
# so the migration file is pure ASCII and no clipboard or editor can garble it
# again. Values come from the generated 069/070 files, which are correct UTF-8.
# Run: python3 -B supabase/geography/repair-071.py
import base64, hashlib, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MIG = ROOT / 'supabase/migrations'
q = r"'((?:[^']|'')*)'"
unq = lambda s: s.replace("''", "'")
b64 = lambda s: base64.b64encode(s.encode('utf-8')).decode('ascii')
val = lambda s: f"convert_from(decode('{b64(s)}', 'base64'), 'UTF8')"

badges, places = {}, {}
for f in ('069_geography.sql', '070_geography_map.sql'):
    for line in (MIG / f).read_text(encoding='utf-8').splitlines():
        m = re.match(rf"^\({q}, {q}, {q}, ", line)
        if m and m.group(1).startswith('geo_'):
            badges[unq(m.group(1))] = unq(m.group(3))
        m = re.match(rf"^\({q}, '(capital|city)', {q}, ", line)
        if m:
            places[unq(m.group(1))] = unq(m.group(3))

assert len(badges) == 23, len(badges)
assert len(places) == 340, len(places)
fix_places = {k: v for k, v in places.items() if any(ord(c) > 127 for c in v)}

# What the live rows must look like afterwards, as md5 over ALL rows in key
# order, so the check covers the untouched ones too.
md5 = lambda d: hashlib.md5('|'.join(d[k] for k in sorted(d)).encode('utf-8')).hexdigest()
badge_md5, place_md5 = md5(badges), md5(places)

out = [
 '-- 071 - Repair Geography badge emoji and accented place names',
 '--',
 '-- 069 and 070 reached Supabase through a clipboard that was not UTF-8, so',
 f'-- the {len(badges)} Geography badge emoji and {len(fix_places)} accented Pin the map place',
 '-- names were stored garbled (a turtle became three odd characters). This',
 '-- re-sets them from the generated files. Every value is carried as base64,',
 '-- so this file is pure ASCII and cannot be garbled the same way.',
 '--',
 '-- Only icon_emoji and geo_pin_places.name change. No card, point, history,',
 '-- badge award or student row is touched. Re-runnable.',
 '-- Generated by supabase/geography/repair-071.py',
 '',
]
for k in sorted(badges):
    out.append(f"UPDATE achievement_definitions SET icon_emoji = {val(badges[k])} WHERE key = '{k}';")
out.append('')
for k in sorted(fix_places):
    out.append(f"UPDATE geo_pin_places SET name = {val(fix_places[k])} WHERE place_key = '{k}';")
out += [
 '',
 f'-- Expected: badges_ok true, places_ok true, garbled_left 0',
 'SELECT',
 "  (SELECT md5(string_agg(icon_emoji, '|' ORDER BY key COLLATE \"C\")) FROM achievement_definitions",
 f"     WHERE category = 'Geography') = '{badge_md5}'                    AS badges_ok,",
 "  (SELECT md5(string_agg(name, '|' ORDER BY place_key COLLATE \"C\")) FROM geo_pin_places)",
 f"     = '{place_md5}'                                                 AS places_ok,",
 "  (SELECT COUNT(*) FROM achievement_definitions WHERE icon_emoji LIKE '%' || chr(63743) || '%')",
 "   + (SELECT COUNT(*) FROM geo_pin_places WHERE name LIKE '%' || chr(8730) || '%')  AS garbled_left;",
]
sql = '\n'.join(out) + '\n'
bad = [c for c in sql if ord(c) > 127]
if bad: sys.exit(f'refusing to write: non-ASCII characters {bad[:5]}')
code = '\n'.join(l for l in sql.splitlines() if not l.startswith('--'))
# Walk the literals in order (a '' inside one is an escaped quote), and refuse
# any that holds ; $ or -- (the Supabase editor misparses those).
risky = [m.group(0) for m in re.finditer(r"'(?:[^']|'')*'", code) if re.search(r";|\$|--", m.group(0))]
if risky: sys.exit(f'refusing to write: risky literals {risky[:3]}')
(MIG / '071_repair_geo_text.sql').write_text(sql, encoding='ascii')
print(f'wrote supabase/migrations/071_repair_geo_text.sql: {len(badges)} badge emoji, {len(fix_places)} place names, all ASCII')
