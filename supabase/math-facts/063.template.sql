ON CONFLICT (key) DO UPDATE SET
  label = EXCLUDED.label, icon_emoji = EXCLUDED.icon_emoji,
  description = EXCLUDED.description, rarity = EXCLUDED.rarity,
  creature = EXCLUDED.creature, category = EXCLUDED.category,
  lore = EXCLUDED.lore, threshold = EXCLUDED.threshold;


-- ── 2. Awarding ──────────────────────────────────────────────────────────────
--
-- award_fact_badges_for does the work for any student. It is NOT callable by
-- users (revoked below): otherwise anyone could award badges to anyone.
-- Students call award_fact_badges, which only ever acts on themselves.
-- Returns the keys newly awarded by this call.

CREATE OR REPLACE FUNCTION award_fact_badges_for(p_user UUID, p_perfect_round BOOLEAN DEFAULT FALSE)
RETURNS SETOF TEXT
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  WITH f AS (
    SELECT c.op, c.a, c.b, c.form, (h.fluent_at IS NOT NULL) AS fluent
    FROM math_fact_cards c
    LEFT JOIN fact_history h ON h.fact_key = c.fact_key AND h.user_id = p_user
  ),
  earned(key) AS (
    SELECT 'facts_mastered_' || t FROM unnest(ARRAY[10, 50, 100, 250, 500, 864]) AS t
     WHERE (SELECT COUNT(*) FROM f WHERE fluent) >= t
    UNION ALL
    SELECT 'facts_table_' || n FROM generate_series(1, 12) AS n
     WHERE NOT EXISTS (SELECT 1 FROM f WHERE op = 'mul' AND (a = n OR b = n) AND NOT fluent)
    UNION ALL
    SELECT 'facts_all_' || o FROM unnest(ARRAY['mul', 'div']) AS o
     WHERE NOT EXISTS (SELECT 1 FROM f WHERE op = o AND NOT fluent)
    UNION ALL
    SELECT 'facts_missing_' || t FROM unnest(ARRAY[25, 100]) AS t
     WHERE (SELECT COUNT(*) FROM f WHERE fluent AND form <> 'c') >= t
    UNION ALL
    SELECT 'facts_perfect_round' WHERE p_perfect_round
  )
  INSERT INTO user_achievements (user_id, achievement_key)
  SELECT p_user, e.key
    FROM earned e
    JOIN achievement_definitions d ON d.key = e.key
   WHERE EXISTS (SELECT 1 FROM profiles p WHERE p.id = p_user)
  ON CONFLICT (user_id, achievement_key) DO NOTHING
  RETURNING achievement_key;
$$;

REVOKE ALL ON FUNCTION award_fact_badges_for(UUID, BOOLEAN) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION award_fact_badges(p_perfect_round BOOLEAN DEFAULT FALSE)
RETURNS SETOF TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'award_fact_badges requires a signed-in user';
  END IF;
  RETURN QUERY SELECT k FROM award_fact_badges_for(auth.uid(), p_perfect_round) AS k;
END;
$$;

REVOKE ALL ON FUNCTION award_fact_badges(BOOLEAN) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION award_fact_badges(BOOLEAN) TO authenticated;


-- ── 3. Award what students have already earned ───────────────────────────────

DO $$
DECLARE
  r RECORD;
BEGIN
  FOR r IN SELECT DISTINCT user_id FROM fact_history LOOP
    PERFORM award_fact_badges_for(r.user_id, FALSE);
  END LOOP;
END $$;


-- ── Verification ─────────────────────────────────────────────────────────────
--
-- Expected: math_badges __COUNT__, helper_callable_by_students false,
--           awarded = Math Facts badges held right now (more than 0 if anyone
--           has mastered 10 or more cards).

SELECT
  (SELECT COUNT(*) FROM achievement_definitions WHERE category = 'Math Facts') AS math_badges,
  has_function_privilege('authenticated', 'award_fact_badges_for(uuid, boolean)', 'EXECUTE')
                                                                               AS helper_callable_by_students,
  (SELECT COUNT(*) FROM user_achievements WHERE achievement_key LIKE 'facts_%') AS awarded;
