-- 063 — Math Facts badges
--
-- A "Math Facts" badge category, shown in the Bestiary and on profiles like
-- every other. __COUNT__ badges:
--
--   Calcupede          10 / 50 / 100 / 250 / 500 / all 864 cards mastered
--   Master of the Ns   every x-card for one times table, all 3 card types (69 each)
--   Monarch / Duchess  all 432 multiplication / all 432 division cards
--   Detective / Sleuth 25 / 100 missing-number cards mastered
--   Flawless Ten       a 10-card round, every card right and fast
--
-- Everything except Flawless Ten is computed in SQL from fact_history, so a
-- badge can only be awarded for mastery that is really recorded. Flawless
-- Ten is a property of one session and is reported by the client, the same
-- trust every other badge already has.
--
-- Additive. Badges are only ever inserted, never removed, and nothing here
-- reads or writes Clutch Points or Fact Points. Re-running is harmless: the
-- definitions upsert and awards ignore duplicates. Students who already
-- qualify are awarded at the end.
--
-- Content is generated by supabase/math-facts/badges.py, which refuses ; $ and -- inside string
-- literals (the Supabase editor misparses them).


-- ── 1. Badge definitions ─────────────────────────────────────────────────────

INSERT INTO achievement_definitions (key, label, icon_emoji, description, rarity, creature, category, lore, threshold) VALUES

