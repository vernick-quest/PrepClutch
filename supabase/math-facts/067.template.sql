-- 067 — Math Facts badges: a balanced ladder on every tab
--
-- Before this, the ÷ tab had one badge (all 432 division cards) and the
-- fraction tabs jumped from 25 straight to everything. Now every tab climbs
-- the same way, first 10 cards, halfway, then all of it, and division gets
-- a badge per table to mirror Master of the 1s-12s.
--
--   × Multiply   10, 216 (new)   then Multiplication Monarch (all 432)
--   ÷ Divide     10, 216 (new)   then Division Duchess (all 432)
--                Master of ÷1s ... ÷12s (new): every division card in that
--                table's family, divisor or answer, all three card types
--   ½ Fractions  10, 152 (new)   alongside 25 and all 304
--   % Decimals   10, 45  (new)   alongside 25 and all 90
--
-- 20 new badges. Nothing existing changes and nothing is ever removed.
-- Students who already qualify are awarded at the end. Re-runnable.
-- Generated by supabase/math-facts/ladders.py, which refuses ; $ and --
-- inside string literals.


