-- ── 2. Awarding ──────────────────────────────────────────────────────────────
--
-- Same function as 064 with the new rungs added. Each count is pinned to its
-- tab (topic, and op for times tables), so a fraction card can never count
-- toward a division badge.

CREATE OR REPLACE FUNCTION award_fact_badges_for(p_user UUID, p_perfect_round BOOLEAN DEFAULT FALSE)
RETURNS SETOF TEXT
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  WITH f AS (
    SELECT c.topic, c.op, c.a, c.b, c.form, (h.fluent_at IS NOT NULL) AS fluent
    FROM math_fact_cards c
    LEFT JOIN fact_history h ON h.fact_key = c.fact_key AND h.user_id = p_user
  ),
  earned(key) AS (
    SELECT 'facts_mastered_' || t FROM unnest(ARRAY[10, 50, 100, 250, 500]) AS t
     WHERE (SELECT COUNT(*) FROM f WHERE fluent) >= t
    UNION ALL
    SELECT 'facts_mastered_864'
     WHERE NOT EXISTS (SELECT 1 FROM f WHERE topic = 'times' AND NOT fluent)
    UNION ALL
    -- × and ÷ ladders
    SELECT 'facts_' || o || '_' || t
      FROM unnest(ARRAY['mul', 'div']) AS o CROSS JOIN unnest(ARRAY[10, 216]) AS t
     WHERE (SELECT COUNT(*) FROM f WHERE topic = 'times' AND op = o AND fluent) >= t
    UNION ALL
    SELECT 'facts_table_' || n FROM generate_series(1, 12) AS n
     WHERE NOT EXISTS (SELECT 1 FROM f WHERE topic = 'times' AND op = 'mul' AND (a = n OR b = n) AND NOT fluent)
    UNION ALL
    SELECT 'facts_divtable_' || n FROM generate_series(1, 12) AS n
     WHERE NOT EXISTS (SELECT 1 FROM f WHERE topic = 'times' AND op = 'div' AND (a = n OR b = n) AND NOT fluent)
    UNION ALL
    SELECT 'facts_all_' || o FROM unnest(ARRAY['mul', 'div']) AS o
     WHERE NOT EXISTS (SELECT 1 FROM f WHERE topic = 'times' AND op = o AND NOT fluent)
    UNION ALL
    SELECT 'facts_missing_' || t FROM unnest(ARRAY[25, 100]) AS t
     WHERE (SELECT COUNT(*) FROM f WHERE topic = 'times' AND fluent AND form <> 'c') >= t
    UNION ALL
    -- ½ and % ladders
    SELECT 'facts_' || r.tp || '_' || r.t
      FROM (VALUES ('equiv', 10), ('equiv', 25), ('equiv', 152),
                   ('fdp', 10), ('fdp', 25), ('fdp', 45)) AS r(tp, t)
     WHERE (SELECT COUNT(*) FROM f WHERE topic = r.tp AND fluent) >= r.t
    UNION ALL
    SELECT 'facts_' || tp || '_all' FROM unnest(ARRAY['equiv', 'fdp']) AS tp
     WHERE NOT EXISTS (SELECT 1 FROM f WHERE topic = tp AND NOT fluent)
    UNION ALL
    SELECT 'facts_perfect_round' WHERE p_perfect_round
  )
  INSERT INTO user_achievements (user_id, achievement_key)
  SELECT p_user, e.key
    FROM earned e
    JOIN achievement_definitions d ON d.key = e.key
   WHERE EXISTS (SELECT 1 FROM profiles p WHERE p.id = p_user)
  ON CONFLICT (user_id, achievement_key) DO NOTHING
  RETURNING achievement_key;
$$;

REVOKE ALL ON FUNCTION award_fact_badges_for(UUID, BOOLEAN) FROM PUBLIC, anon, authenticated;


-- ── 3. Award what students have already earned ───────────────────────────────

DO $$
DECLARE
  r RECORD;
BEGIN
  FOR r IN SELECT DISTINCT user_id FROM fact_history LOOP
    PERFORM award_fact_badges_for(r.user_id, FALSE);
  END LOOP;
END $$;


-- ── Verification ─────────────────────────────────────────────────────────────
--
-- Expected: math_badges 47, new_badges 20, helper_callable_by_students false,
--           awarded = Math Facts badges held right now (it can only go up).

SELECT
  (SELECT COUNT(*) FROM achievement_definitions WHERE category = 'Math Facts') AS math_badges,
  (SELECT COUNT(*) FROM achievement_definitions
    WHERE key IN ('facts_mul_10', 'facts_mul_216', 'facts_div_10', 'facts_div_216',
                  'facts_equiv_10', 'facts_equiv_152', 'facts_fdp_10', 'facts_fdp_45')
       OR key LIKE 'facts_divtable_%')                                     AS new_badges,
  has_function_privilege('authenticated', 'award_fact_badges_for(uuid, boolean)', 'EXECUTE')
                                                                           AS helper_callable_by_students,
  (SELECT COUNT(*) FROM user_achievements WHERE achievement_key LIKE 'facts_%') AS awarded;
