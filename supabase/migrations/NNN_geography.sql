CREATE TABLE IF NOT EXISTS geo_history (
  user_id          UUID        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  card_key         TEXT        NOT NULL,
  times_correct    INT         NOT NULL DEFAULT 0,
  times_wrong      INT         NOT NULL DEFAULT 0,
  best_ms          INT,
